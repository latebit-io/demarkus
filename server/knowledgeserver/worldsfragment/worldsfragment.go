// Package worldsfragment is the worlds fragment a provisioner generates from
// its tenant registry: the one shape the broker writes and the knowledge
// server reads, so the two cannot drift apart in separate modules.
package worldsfragment

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

// Header opens every generated fragment. A comment, so a build that predates
// it reads the document unchanged; the server tells a generated fragment
// from an operator's file by it.
const Header = "# Generated by the demarkus broker from its tenant registry; do not edit.\n"

// Doc is the fragment document.
type Doc struct {
	Worlds []World `yaml:"worlds"`
}

// World is one provisioned tenant world. A field added here reaches a server
// of an older build as an unknown key, which Parse skips and reports.
type World struct {
	Name        string   `yaml:"name"`
	Authorities []string `yaml:"authorities"`
	Bucket      Bucket   `yaml:"bucket"`
	Limits      *Limits  `yaml:"limits,omitempty"`
	Policy      *Policy  `yaml:"policy,omitempty"`
	// Gated keeps the tenant off the capability listener: its reads are the
	// owner's through the bearer gate, never anonymous.
	Gated bool `yaml:"gated"`
	// Seed names the policy the server seeds the world with; "" is the
	// knowledge default. The server alone seeds: no broker writes one.
	Seed string `yaml:"seed,omitempty"`
}

// SeedMemory is the Seed of a personal memory: the tenant policy.
const SeedMemory = "memory"

// Bucket is the tenant's store.
type Bucket struct {
	URL     string `yaml:"url"`
	WorldID string `yaml:"worldID"`
}

// Limits is the tenant's quota.
type Limits struct {
	MaxDocuments int `yaml:"maxDocuments"`
}

// Policy opens governance on a tenant, whose owner curates their own layout
// and policy.
type Policy struct {
	Governance string `yaml:"governance"`
}

// Render is the document a provisioner stores: Header, then worlds by name.
func Render(worlds []World) ([]byte, error) {
	sorted := slices.Clone(worlds)
	slices.SortFunc(sorted, func(a, b World) int { return strings.Compare(a.Name, b.Name) })
	if sorted == nil {
		sorted = []World{}
	}
	body, err := yaml.Marshal(Doc{Worlds: sorted})
	if err != nil {
		return nil, fmt.Errorf("render worlds fragment: %w", err)
	}
	return append([]byte(Header), body...), nil
}

// Generated reports whether data is a provisioner's fragment.
func Generated(data []byte) bool {
	return bytes.HasPrefix(data, []byte(Header))
}

// Parse reads a generated fragment. Keys this build does not know are
// skipped and described in unknown, so a newer provisioner's fragment still
// converges on a server mid-rollout.
func Parse(data []byte) (doc Doc, unknown string, err error) {
	strictErr := decode(data, true, &doc)
	if strictErr == nil {
		return doc, "", nil
	}
	doc = Doc{}
	if err := decode(data, false, &doc); err != nil {
		return Doc{}, "", err
	}
	return doc, strictErr.Error(), nil
}

// decode reads exactly one document; none at all is an empty Doc.
func decode(data []byte, strict bool, doc *Doc) error {
	decoder := yaml.NewDecoder(bytes.NewReader(data))
	decoder.KnownFields(strict)
	if err := decoder.Decode(doc); err != nil {
		if errors.Is(err, io.EOF) {
			return nil
		}
		return fmt.Errorf("parse worlds fragment: %w", err)
	}
	var trailing any
	if err := decoder.Decode(&trailing); !errors.Is(err, io.EOF) {
		return errors.New("parse worlds fragment: more than one document")
	}
	return nil
}
